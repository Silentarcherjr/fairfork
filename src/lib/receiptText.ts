import type { Alternative } from '../types/alternatives';
import type { Horizon, Timeline } from '../types/billing';
import type { RankResult, RankedCandidate } from '../types/ranking';
import type { OfferTerms } from '../types/terms';
import { ALTERNATIVES } from '../data/alternatives';
import { formatMoney } from './money';
import { collectUnknowns } from './unknowns';

export const RECEIPT_WIDTH = 46;

/** Offer cost minus best-fit cost over the same horizon — only when both are known, in USD, and the best fit is another plan. */
export function switchDifferenceMinor(timeline: Timeline | null, bestFit: RankedCandidate | null): number | null {
  if (
    timeline?.status === 'known' &&
    bestFit &&
    !bestFit.isUserOffer &&
    bestFit.horizonCostMinor !== null &&
    timeline.currency === 'USD' &&
    bestFit.currency === 'USD'
  ) {
    return timeline.totalMinor - bestFit.horizonCostMinor;
  }
  return null;
}

/** "LABEL ........ VALUE" padded to `width` characters (at least two dots). */
export function leader(label: string, value: string, width = RECEIPT_WIDTH): string {
  const dots = Math.max(2, width - label.length - value.length - 2);
  return `${label} ${'.'.repeat(dots)} ${value}`;
}

function signedMoney(minor: number): string {
  if (minor === 0) return formatMoney(0, 'USD');
  return `${minor > 0 ? '−' : '+'}${formatMoney(Math.abs(minor), 'USD')}`;
}

export type ReceiptInput = {
  terms: OfferTerms | null;
  timeline: Timeline | null;
  rankResult: RankResult;
  horizon: Horizon;
  startDate: string;
  verifiedAt: string;
  alternatives?: Alternative[];
};

/** Plain-text, monospace-friendly receipt for copying. */
export function buildReceiptText({
  terms,
  timeline,
  rankResult,
  horizon,
  startDate,
  verifiedAt,
  alternatives = ALTERNATIVES,
}: ReceiptInput): string {
  const rule = '-'.repeat(RECEIPT_WIDTH);
  const months = `${horizon} MO`;
  const out: string[] = [];

  out.push('FAIRFORK RECEIPT');
  out.push('This offer — according to the pasted text');
  out.push(leader('Start date', startDate));

  if (terms?.trialDays.status === 'found') {
    const d = terms.trialDays.value;
    out.push(leader('Free trial', `${d} ${d === 1 ? 'day' : 'days'}`));
  }

  if (timeline?.status === 'known') {
    const n = timeline.charges.length;
    const amounts = new Set(timeline.charges.map((c) => c.amountMinor));
    const each = n > 0 && amounts.size === 1 ? ` × ${formatMoney(timeline.charges[0].amountMinor, timeline.currency)}` : '';
    out.push(leader(`${n} ${n === 1 ? 'charge' : 'charges'}${each}`, formatMoney(timeline.totalMinor, timeline.currency)));
    if (n > 0) out.push(leader('First charge', timeline.firstChargeDate));
    out.push(rule);
    out.push(leader(`TOTAL / ${months}`, formatMoney(timeline.totalMinor, timeline.currency)));
  } else {
    out.push(rule);
    out.push(leader(`TOTAL / ${months}`, 'Unknown'));
    if (timeline?.status === 'unknown') out.push(`(${timeline.reason})`);
  }

  const assumptions = timeline?.assumptions ?? [];
  if (assumptions.length > 0) {
    out.push('Assumptions:');
    for (const a of assumptions) out.push(`- ${a}`);
  }

  out.push(rule);
  out.push('BEST FIT FOR YOU');
  const best = rankResult.bestFit;
  let sources: string[] = [];
  if (rankResult.noneQualifies || !best) {
    out.push('No option meets all your requirements.');
  } else {
    const cost = best.horizonCostMinor !== null && best.currency ? formatMoney(best.horizonCostMinor, best.currency) : 'Unknown';
    out.push(leader(best.label, cost));
    for (const r of best.reasons) out.push(`- ${r}`);
    const diff = switchDifferenceMinor(timeline, best);
    if (diff !== null) {
      out.push(leader('IF YOU SWITCH', `${signedMoney(diff)}*`));
      out.push(`* over ${horizon === 1 ? '1 month' : `${horizon} months`}, if both start on ${startDate} and you don't cancel.`);
    }
    if (best.isUserOffer) {
      out.push('(Judged only by what the pasted text says.)');
    } else {
      const alt = alternatives.find((a) => a.id === best.alternativeId);
      if (alt) {
        const priceUrl = alt.prices.find((p) => p.period === best.period)?.sourceUrl;
        sources = [...new Set([alt.officialUrl, ...(priceUrl ? [priceUrl] : [])])];
      }
    }
  }

  const unknownCount = collectUnknowns(terms, alternatives).length;
  out.push(rule);
  out.push(`Unknowns: ${unknownCount} ${unknownCount === 1 ? 'fact' : 'facts'} not stated or not verified`);
  if (sources.length > 0) {
    out.push('Sources:');
    for (const s of sources) out.push(`- ${s}`);
  }
  out.push(`Curated catalog verified on ${verifiedAt}`);
  out.push('Generated by FairFork — not financial or legal advice');
  return out.join('\n');
}
