import { describe, expect, it } from 'vitest';
import { buildReceiptText, leader, switchDifferenceMinor, RECEIPT_WIDTH, MAX_RECEIPT_QUESTIONS } from '../src/lib/receiptText';
import { collectUnknowns, questionFor } from '../src/lib/unknowns';
import { parseOffer } from '../src/lib/parseOffer';
import { calculateBillingTimeline } from '../src/lib/billing';
import { buildCandidates, rankOptions } from '../src/lib/ranking';
import { ALTERNATIVES, CATALOG_VERIFIED_AT } from '../src/data/alternatives';
import { EXAMPLE_OFFER } from '../src/data/exampleOffer';
import type { Horizon } from '../src/types/billing';
import type { Preferences } from '../src/types/ranking';

const START = '2026-11-01';
const noPrefs: Preferences = { maxMonthlyBudgetMinor: null, mustHave: { ide: false, annualBilling: false, monthlyCancel: false } };

function receiptFor(text: string, prefs: Preferences = noPrefs, horizon: Horizon = 12) {
  const terms = parseOffer(text);
  const timeline = calculateBillingTimeline(terms, START, horizon);
  const candidates = buildCandidates(terms, timeline, ALTERNATIVES, START, horizon);
  const rankResult = rankOptions(candidates, prefs, horizon);
  const receipt = buildReceiptText({ terms, timeline, rankResult, horizon, startDate: START, verifiedAt: CATALOG_VERIFIED_AT });
  return { receipt, timeline, rankResult };
}

describe('leader', () => {
  it('pads to the receipt width with dots', () => {
    const line = leader('TOTAL', '$1.00');
    expect(line).toHaveLength(RECEIPT_WIDTH);
    expect(line).toMatch(/^TOTAL \.+ \$1\.00$/);
  });
  it('keeps at least two dots for long labels', () => {
    expect(leader('x'.repeat(60), '$1.00')).toContain(' .. $1.00');
  });
});

describe('buildReceiptText', () => {
  it('example offer: trial, charges × price, first charge, total, assumptions, best fit, switch, sources, disclaimer', () => {
    const { receipt, rankResult } = receiptFor(EXAMPLE_OFFER);
    const lines = receipt.split('\n');
    expect(lines.length).toBeGreaterThanOrEqual(15);
    expect(lines.length).toBeLessThanOrEqual(40);
    expect(receipt).toMatch(/Free trial \.+ 7 days/);
    expect(receipt).toMatch(/12 charges × \$19\.99 \.+ \$239\.88/);
    expect(receipt).toMatch(/First charge \.+ 2026-11-08/);
    expect(receipt).toMatch(/TOTAL \/ 12 MO \.+ \$239\.88/);
    expect(receipt).toContain("Assuming you don't cancel before each charge.");
    expect(receipt).toContain('BEST FIT FOR YOU');
    expect(receipt).toContain(rankResult.bestFit!.label);
    for (const r of rankResult.bestFit!.reasons) expect(receipt).toContain(r);
    expect(receipt).toMatch(/IF YOU SWITCH \.+ −\$119\.88\*/);
    expect(receipt).toContain("if both start on 2026-11-01 and you don't cancel");
    expect(receipt).toMatch(/Unknowns: \d+ facts? not stated or not verified/);
    expect(receipt).toMatch(/Sources:\n- https:\/\//);
    expect(receipt).toContain(`Curated catalog verified on ${CATALOG_VERIFIED_AT}`);
    expect(receipt).toContain('Generated by FairFork — not financial or legal advice');
    expect(receipt).not.toMatch(/\bwill save\b/i);
  });

  it('unknown price → total "Unknown", never $0, and no switch line', () => {
    const { receipt } = receiptFor('Start your 7-day free trial. Renews automatically.');
    expect(receipt).toMatch(/TOTAL \/ 12 MO \.+ Unknown/);
    expect(receipt).not.toMatch(/\$0\.00/);
    expect(receipt).not.toContain('IF YOU SWITCH');
  });

  it('non-USD offer → no switch difference', () => {
    const { receipt } = receiptFor('€9/month, renews automatically.');
    expect(receipt).toContain('€108.00');
    expect(receipt).not.toContain('IF YOU SWITCH');
  });

  it('no qualifying option → says so, no sources', () => {
    const { receipt } = receiptFor(EXAMPLE_OFFER, { ...noPrefs, maxMonthlyBudgetMinor: 100 });
    expect(receipt).toContain('No option meets all your requirements.');
    expect(receipt).not.toContain('IF YOU SWITCH');
    expect(receipt).not.toContain('Sources:');
  });

  it('follows the horizon', () => {
    const { receipt } = receiptFor(EXAMPLE_OFFER, noPrefs, 3);
    expect(receipt).toMatch(/TOTAL \/ 3 MO \.+ \$59\.97/);
  });

  it('switchDifferenceMinor is null without a known timeline or when the best fit is your offer', () => {
    const { timeline, rankResult } = receiptFor(EXAMPLE_OFFER);
    expect(switchDifferenceMinor(null, rankResult.bestFit)).toBeNull();
    expect(switchDifferenceMinor(timeline, { ...rankResult.bestFit!, isUserOffer: true })).toBeNull();
    expect(switchDifferenceMinor(timeline, rankResult.bestFit)).toBe(23988 - rankResult.bestFit!.horizonCostMinor!);
  });

  it('"Ask before you pay" lists questions about your offer and the best fit only, capped', () => {
    const { receipt, rankResult } = receiptFor(EXAMPLE_OFFER);
    expect(receipt).toContain('ASK BEFORE YOU PAY');
    const section = receipt.split('ASK BEFORE YOU PAY\n')[1].split('\nCurated catalog')[0];
    const qLines = section.split('\n').filter((l) => l.startsWith('- ') && !l.startsWith('- https'));
    const best = ALTERNATIVES.find((a) => a.id === rankResult.bestFit!.alternativeId)!;
    const bestLabel = `${best.provider} ${best.plan}`;
    const expected = collectUnknowns(parseOffer(EXAMPLE_OFFER), ALTERNATIVES).filter(
      (u) => u.option === 'Your offer' || u.option === bestLabel,
    );
    const shown = qLines.filter((l) => !l.includes('more in'));
    expect(shown.length).toBe(Math.min(expected.length, MAX_RECEIPT_QUESTIONS));
    for (const u of expected.slice(0, MAX_RECEIPT_QUESTIONS)) expect(section).toContain(`- ${u.option}: ${questionFor(u)}`);
    for (const l of shown) expect(l.startsWith('- Your offer:') || l.startsWith(`- ${bestLabel}:`)).toBe(true);
  });

  it('caps the questions and points to the ledger for the rest', () => {
    const { receipt } = receiptFor('hello world, nothing here');
    const section = receipt.split('ASK BEFORE YOU PAY\n')[1].split('\nCurated catalog')[0];
    const shown = section.split('\n').filter((l) => l.startsWith('- ') && !l.startsWith('- https') && !l.includes('more in'));
    expect(shown.length).toBe(MAX_RECEIPT_QUESTIONS);
    expect(section).toMatch(/…and \d+ more in "What nobody told you"/);
  });
});
